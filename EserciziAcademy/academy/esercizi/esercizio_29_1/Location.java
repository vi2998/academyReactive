package academy.esercizi.esercizio_29_1;

public class Location {
    private int riga;
    private int colonna;

    public Location(int riga, int colonna) {
        this.riga = riga;
        this.colonna = colonna;
    }

    public int getRiga() {
        return riga;
    }

    public int getColonna() {
        return colonna;
    }


}
